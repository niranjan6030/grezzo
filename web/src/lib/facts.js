/* ------------------------------------------------------------------
   Rotation.

   There is no denim-facts API worth pointing a shop at — the options are
   scraping something unverifiable or generating text, and both mean
   publishing claims nobody checked. So the library is curated and the
   *selection* rotates instead: a deterministic shuffle seeded by the
   half-day, served from /api/facts.

   Deterministic matters. Everyone sees the same facts for the same twelve
   hours, the server and the browser agree, and nothing reshuffles under
   someone mid-read.
   ------------------------------------------------------------------ */

/** Mulberry32 — small, fast, and identical on both sides of the wire. */
function seeded(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export const periodFor = (at = Date.now()) => Math.floor(at / ROTATION_MS);

/** When the current selection gives way to the next one. */
export const nextRotationAt = (at = Date.now()) => new Date((periodFor(at) + 1) * ROTATION_MS);

/**
 * The facts on show right now. `count` of them, shuffled by the half-day,
 * so a visitor this morning and a visitor this evening see different ones.
 */
export function factsForNow(count = 12, at = Date.now()) {
  const rand = seeded(periodFor(at) * 2654435761);
  const pool = [...DENIM_FACTS];

  // Fisher-Yates, driven by the seeded generator.
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, Math.min(count, pool.length));
}
